    // ── Cellule parsée ───────────────────────────────────────────────────────
    private struct Cell
    {
        public byte CharIndex; // byte CP437 direct (0-255)
        public byte Fg;        // index couleur 0-15
        public byte Bg;        // index couleur 0-7
    }

    // ── Points d'entrée publics ───────────────────────────────────────────────

    /// <summary>
    /// Rend un fichier ANSI depuis un tableau de bytes.
    /// DOIT être appelé sur le thread UI (crée un WriteableBitmap).
    /// </summary>
    public static BitmapSource RenderFromBytes(byte[] data, int cols = 80)
    {
        var stripped      = StripSauce(data);
        var (cells, rows) = Parse(stripped, cols);
        return DrawBitmap(cells, cols, rows);
    }

    /// <summary>Rend depuis un Stream. DOIT être appelé sur le thread UI.</summary>
    public static BitmapSource Render(Stream stream, int cols = 80)
    {
        using var ms = new MemoryStream();
        stream.CopyTo(ms);
        return RenderFromBytes(ms.ToArray(), cols);
    }

    // ── Strip SAUCE record ───────────────────────────────────────────────────
    private static byte[] StripSauce(byte[] data)
    {
        if (data.Length >= 128)
        {
            int off = data.Length - 128;
            if (data[off]     == 'S' && data[off + 1] == 'A' && data[off + 2] == 'U' &&
                data[off + 3] == 'C' && data[off + 4] == 'E' && data[off + 5] == '0')
            {
                int sub = -1;
                for (int i = off - 1; i >= 0; i--)
                    if (data[i] == 0x1A) { sub = i; break; }
                return sub >= 0 ? data[..sub] : data[..off];
            }
        }
        return data;
    }

    // ── Parsing ANSI ─────────────────────────────────────────────────────────
    private static (Cell[,] cells, int rows) Parse(byte[] data, int cols)
    {
        int maxRows = Math.Max(data.Length / cols + 10, 300);
        var cells   = new Cell[maxRows, cols];

        byte curFg = 7, curBg = 0;
        bool bold   = false;
        int  cx = 0, cy = 0;
        int  savedCx = 0, savedCy = 0;
        int  lastRow = 0;

        for (int r = 0; r < maxRows; r++)
            for (int c = 0; c < cols; c++)
                cells[r, c] = new Cell { CharIndex = 0x20, Fg = 7, Bg = 0 };

        int i = 0;
        while (i < data.Length)
        {
            byte b = data[i++];

            if (b == 0x1B && i < data.Length && data[i] == (byte)'[')
            {
                i++;
                var pb = new StringBuilder();
                while (i < data.Length && (data[i] == (byte)';' || data[i] >= '0' && data[i] <= '9'))
                    pb.Append((char)data[i++]);
                if (i >= data.Length) break;
                char cmd = (char)data[i++];

                var parts = pb.Length > 0 ? pb.ToString().Split(';') : (string[])[""];
                int P(int idx = 0, int def = 1)
                {
                    var v = idx < parts.Length ? parts[idx] : "";
                    return v.Length > 0 && int.TryParse(v, out int rv) ? rv : def;
                }

                switch (cmd)
                {
                    case 'm':
                        foreach (var part in parts)
                        {
                            int n = part.Length > 0 && int.TryParse(part, out int pn) ? pn : 0;
                            switch (n)
                            {
                                case 0:              curFg = 7; curBg = 0; bold = false; break;
                                case 1:              bold = true;  break;
                                case 2: case 22:     bold = false; break;
                                case >= 30 and <= 37: curFg = (byte)(n - 30); break;
                                case 39:             curFg = 7;    break;
                                case >= 40 and <= 47: curBg = (byte)(n - 40); break;
                                case 49:             curBg = 0;    break;
                                case >= 90 and <= 97:   curFg = (byte)(n - 90  + 8); break;
                                case >= 100 and <= 107: curBg = (byte)(n - 100 + 8); break;
                            }
                        }
                        break;
                    case 'A': cy = Math.Max(0,          cy - P()); break;
                    case 'B': cy = Math.Min(maxRows - 1, cy + P()); break;
                    case 'C': cx = Math.Min(cols - 1,    cx + P()); break;
                    case 'D': cx = Math.Max(0,            cx - P()); break;
                    case 'H': case 'f':
                        cy = Math.Clamp(P(0, 1) - 1, 0, maxRows - 1);
                        cx = Math.Clamp(P(1, 1) - 1, 0, cols - 1);
                        break;
                    case 'J':
                        if (P(0, 0) is 2 or 3)
                        {
                            cx = 0; cy = 0; lastRow = 0;
                            for (int r = 0; r < maxRows; r++)
                                for (int c = 0; c < cols; c++)
                                    cells[r, c] = new Cell { CharIndex = 0x20, Fg = 7, Bg = 0 };
                        }
                        break;
                    case 's': savedCx = cx; savedCy = cy; break;
                    case 'u': cx = savedCx; cy = savedCy; break;
                }
            }
            else if (b == 0x0D) { cx = 0; }
            else if (b == 0x0A)
            {
                cy = Math.Min(cy + 1, maxRows - 1);
                if (cy > lastRow) lastRow = cy;
            }
            else
            {
                // Caractère CP437 — le byte EST l'index dans FontData
                if (cy < maxRows && cx < cols)
                {
                    byte fgIdx = bold && curFg < 8 ? (byte)(curFg + 8) : curFg;
                    cells[cy, cx] = new Cell { CharIndex = b, Fg = fgIdx, Bg = curBg };
                    if (cy > lastRow) lastRow = cy;
                }
                if (++cx >= cols)
                {
                    cx = 0;
                    if (++cy >= maxRows) break;
                    if (cy > lastRow) lastRow = cy;
                }
            }
        }

        return (cells, lastRow + 1);
    }

    // ── Rendu bitmap pixel-par-pixel ─────────────────────────────────────────
    // Même approche que PabloDraw : chaque glyphe = 16 bytes de bits, rendu
    // direct sans police système ni FormattedText.
    private static BitmapSource DrawBitmap(Cell[,] cells, int cols, int rows)
    {
        int imgW   = cols * CharW;
        int imgH   = rows * CharH;
        var pixels = new int[imgW * imgH]; // BGRA en int

        for (int row = 0; row < rows; row++)
        {
            int pixY = row * CharH;

            for (int col = 0; col < cols; col++)
            {
                ref var cell = ref cells[row, col];
                int fg       = (int)Palette[cell.Fg & 15];
                int bg       = (int)Palette[cell.Bg &  7];
                int fontBase = cell.CharIndex * CharH;
                int pixX     = col * CharW;

                for (int fy = 0; fy < CharH; fy++)
                {
                    byte bits   = FontData[fontBase + fy];
                    int  offset = (pixY + fy) * imgW + pixX;
                    pixels[offset + 0] = (bits & 0x80) != 0 ? fg : bg;
                    pixels[offset + 1] = (bits & 0x40) != 0 ? fg : bg;
                    pixels[offset + 2] = (bits & 0x20) != 0 ? fg : bg;
                    pixels[offset + 3] = (bits & 0x10) != 0 ? fg : bg;
                    pixels[offset + 4] = (bits & 0x08) != 0 ? fg : bg;
                    pixels[offset + 5] = (bits & 0x04) != 0 ? fg : bg;
                    pixels[offset + 6] = (bits & 0x02) != 0 ? fg : bg;
                    pixels[offset + 7] = (bits & 0x01) != 0 ? fg : bg;
                }
            }
        }

        var wb = new WriteableBitmap(imgW, imgH, 96, 96, PixelFormats.Bgra32, null);
        wb.WritePixels(new Int32Rect(0, 0, imgW, imgH), pixels, imgW * 4, 0);
        wb.Freeze();
        return wb;
    }
